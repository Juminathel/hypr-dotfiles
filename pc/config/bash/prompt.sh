# Приглашение bash: строки с командами сразу видны среди вывода.
# Подключается из ~/.bashrc:  [ -f ~/.config/bash/prompt.sh ] && . ~/.config/bash/prompt.sh
#
#   ~/hypr-dotfiles-main ❯ ls          ← путь синим, стрелка зелёная
#   ...вывод...
#                                      ← пустая строка перед каждой новой командой
#   ~ 1 ❯                              ← команда завершилась с ошибкой: код и стрелка красные
#
# Метка OSC 133;A говорит foot, где начинается приглашение:
# Ctrl+Shift+Z / Ctrl+Shift+X — прыжок к предыдущей / следующей команде (см. foot.ini).

# Разделитель и код ошибки — только если команда правда выполнялась. На пустой Enter и Ctrl+C
# bash ничего не запускает и оставляет в $? код прошлой команды — его не показываем, строк не плодим.
# Ловушка DEBUG срабатывает перед каждой командой из строки ввода (и перед самим __prompt — его пропускаем);
# внутрь функций она не заходит, а $? после неё bash восстанавливает.
__prompt_ran=
__prompt_shown=
trap '[ "$BASH_COMMAND" = __prompt ] || __prompt_ran=1' DEBUG

__prompt() {
    local status=$?
    local arrow='\[\e[1;32m\]❯'
    if [ -n "$__prompt_ran" ]; then
        [ -n "$__prompt_shown" ] && printf '\n'    # над самым первым приглашением в окне — без пустой строки
        [ "$status" -ne 0 ] && arrow="\[\e[1;31m\]$status ❯"
    fi
    __prompt_ran=
    __prompt_shown=1
    PS1="\[\e]133;A\a\]\[\e[1;34m\]\w $arrow\[\e[0m\] "
}

PROMPT_COMMAND=__prompt
